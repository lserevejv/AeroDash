/**
 * tools/stamp-version.mjs — write js/version.js from the current git checkout.
 *
 *   node tools/stamp-version.mjs
 *
 * The game has no build step, so there is nothing to inject a commit hash at
 * build time. This is the smallest honest substitute: a generated constant,
 * committed alongside the code it describes, refreshed by one command.
 *
 * It exists for exactly one question, which turned out to be the hard one to
 * answer remotely: *is the browser in front of you actually running the code we
 * think it is?* A diagnostic report with no build identity cannot distinguish
 * "the fix did not work" from "you are looking at a cached copy of yesterday".
 *
 * Run it before committing. If it is forgotten, the stamped commit simply
 * refers to the previous one — which the diagnostics panel surfaces as a
 * mismatch against the file dates rather than silently lying.
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function git(...args) {
  try {
    return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch (err) {
    return '';
  }
}

const commit = git('rev-parse', '--short', 'HEAD') || 'unknown';
const branch = git('rev-parse', '--abbrev-ref', 'HEAD') || 'unknown';
const dirty = git('status', '--porcelain') !== '';
const commitDate = git('log', '-1', '--format=%cI') || '';

const body = `/**
 * version.js — GENERATED by tools/stamp-version.mjs. Do not edit by hand.
 *
 * Its only job is to let a diagnostic report state which build the browser is
 * running, so "the fix did not work" can be told apart from "you are looking at
 * a cached copy".
 */

export const BUILD = {
  version: '2.0.0',
  commit: '${commit}',
  branch: '${branch}',
  commitDate: '${commitDate}',
  /** True if the working tree had uncommitted changes when this was stamped. */
  dirty: ${dirty},
  stampedAt: '${new Date().toISOString()}',
};

/** Short human-readable build id, e.g. "2.0.0+ab12cd3". */
export const BUILD_ID = \`\${BUILD.version}+\${BUILD.commit}\${BUILD.dirty ? '-dirty' : ''}\`;
`;

writeFileSync(join(ROOT, 'js', 'version.js'), body, 'utf8');
console.log(`[stamp] js/version.js -> 2.0.0+${commit}${dirty ? '-dirty' : ''}`);
